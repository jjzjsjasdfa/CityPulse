const isoIn = (days: number, hour = 11) => {
  const shanghaiWallClock = new Date(Date.now() + 8 * 60 * 60 * 1000);
  shanghaiWallClock.setUTCDate(shanghaiWallClock.getUTCDate() + days);
  return new Date(
    Date.UTC(
      shanghaiWallClock.getUTCFullYear(),
      shanghaiWallClock.getUTCMonth(),
      shanghaiWallClock.getUTCDate(),
      hour - 8,
    ),
  ).toISOString();
};

